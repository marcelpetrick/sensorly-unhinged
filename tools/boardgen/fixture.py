"""Fixture coordinates from the exact board placements, never a separate grid."""
import math
from .design import TESTPADS

HEADER='''<!-- SPDX-FileCopyrightText: 2026 Marcel Petrick <mail@marcelpetrick.it> -->
<!-- SPDX-License-Identifier: GPL-3.0-or-later -->
# Generated prototype fixture map

Generated by `make gen` from the actual A/B placements. Coordinates are millimetres
from the board top-left, looking through the top of the PCB, x right and y down.
These are bottom copper probe pads. For a bottom view with the origin at the
left edge of the viewed board bounding box, use x_bottom = board width − x_top;
y is unchanged. Do not infer locations from a regular grid.

Every target is a 1.5 mm diameter round pad. Probe tip diameter, travel, lateral
registration, locating ribs and connector clearance remain fixture qualification
requirements. The six moved targets retain their electrical nets.

'''

def section(v,placed):
    refs={p.ref:p for p in placed}
    targets=[(ref,net,refs[ref]) for ref,net in TESTPADS]
    pitch=min(math.dist((a.x,a.y),(b.x,b.y)) for i,(_,_,a) in enumerate(targets)
              for _,_,b in targets[i+1:])
    out=[f'## Variant {v.key.upper()} — {v.revision}\n',
         f'Board width for bottom-view mirroring: **{v.width:.3f} mm**.\n',
         f'Minimum target centre spacing: **{pitch:.3f} mm**.\n',
         '| Target | Net | x (mm) | y (mm) |', '|---|---|---:|---:|']
    for ref,net,p in targets:out.append(f'| {ref} | {net} | {p.x:.3f} | {p.y:.3f} |')
    return '\n'.join(out)+'\n\n'
